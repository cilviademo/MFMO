def flow_manual():
    with open(FLOW_JSON, encoding="utf-8") as fh:
        d = json.load(fh)
    defn = d["properties"]["definition"]
    trig = defn["triggers"]["Request"]
    flow_params = [p.split(" (")[0] for p in defn.get("parameters", {})
                   if p.startswith("MF_")]

    out = io.StringIO()
    out.write("# EOM-02 Submission — manual rebuild, click by click\n\n")
    out.write("Derived action-by-action from the implemented workflow JSON "
              "(`solution/src/Workflows/EOM02Submission-*.json`). Nothing "
              "here is from memory. Build it in the browser designer: "
              "Power Automate → Create → **Instant cloud flow** → trigger "
              "**PowerApps (V2)** → name it `EOM-02 Submission`.\n\n")
    out.write("In this manual edition every solution environment variable "
              "becomes a **flow variable initialized at the top**. Fill "
              "each from your own links sheet.\n\n")

    out.write("## Step 0 — the trigger contract (PowerApps V2 inputs)\n\n")
    out.write("Add one **Text** input per property, named exactly:\n\n")
    for pname, spec in trig["inputs"]["schema"]["properties"].items():
        out.write(f"- [ ] `{pname}`"
                  + (f" (shown as \"{spec['title']}\")" if spec.get("title")
                     else "") + "\n")
    out.write("\nThe app calls `EOM02_Submission.Run(...)` with these in "
              "this order; a missing or renamed input breaks the call "
              "visibly in Studio, which is the good failure mode.\n\n")

    out.write("## Step 0b — Initialize the operator variables\n\n")
    out.write("One **Initialize variable** action per row, Type = String, "
              "placed before everything else. Every value is **OPERATOR "
              "VALUE — from your links sheet**; none ships in this kit.\n\n")
    out.write("| Variable name | Holds |\n|---|---|\n")
    for p in flow_params:
        out.write(f"| `var{p}` | your {p.replace('MF_', '').replace('_', ' ')}"
                  f" — OPERATOR VALUE |\n")
    out.write("\n")

    counter = [0]

    def emit(actions, depth, branch=""):
        order = sorted(actions.items(),
                       key=lambda kv: 0 if not kv[1].get("runAfter") else 1)
        # Preserve chain order by walking runAfter successors.
        emitted, remaining = [], dict(actions)
        chain = [n for n, a in actions.items() if not a.get("runAfter")]
        while chain:
            name = chain.pop(0)
            if name in emitted:
                continue
            emitted.append(name)
            nxt = [n for n, a in remaining.items()
                   if name in (a.get("runAfter") or {})]
            chain = nxt + chain
        for name in emitted:
            node = actions[name]
            counter[0] += 1
            t = node.get("type")
            disp = DESIGNER_NAME.get(t) or t
            if t == "OpenApiConnection":
                op = node["inputs"]["host"].get("operationId", "")
                conn = node["inputs"]["host"].get("connectionName", "")
                disp = OPERATION_NAME.get(op, f"{conn} — {op}")
            pretty = name.replace("_", " ")
            h = "#" * min(3 + depth, 6)
            out.write(f"{h} {counter[0]}. {branch}Add **{disp}** — rename "
                      f"it exactly: `{pretty}`\n\n")
            if name in WHY:
                out.write(f"> {WHY[name]}\n\n")
            ra = node.get("runAfter") or {}
            if ra:
                for prev, conds in ra.items():
                    out.write(f"Run after: `{prev.replace('_', ' ')}` "
                              f"[{', '.join(conds)}]\n\n")
            if t == "If":
                expr = json.dumps(node.get("expression", {}), indent=2)
                out.write("Condition (use **Edit in advanced mode** and "
                          "paste verbatim):\n\n```\n"
                          + _sub_params(expr) + "\n```\n\n")
            inputs = node.get("inputs")
            params = inputs.get("parameters") if isinstance(inputs, dict) \
                else None
            if t in ("InitializeVariable",):
                out.write("Inputs:\n\n```json\n"
                          + _sub_params(json.dumps(node.get("inputs", {}),
                                                   indent=2)) + "\n```\n\n")
            elif t in ("Compose", "Response", "Terminate"):
                out.write("Inputs (paste each expression verbatim):\n\n"
                          "```json\n"
                          + _sub_params(json.dumps(inputs, indent=2))
                          + "\n```\n\n")
            elif params:
                out.write("| Parameter | Value (verbatim) |\n|---|---|\n")
                for k, v in params.items():
                    if k == "$authentication" or k.startswith("$auth"):
                        continue
                    vv = _sub_params(json.dumps(v)) if not isinstance(v, str) \
                        else _sub_params(v)
                    out.write(f"| `{k}` | `{vv}` |\n")
                out.write("\n")
            for key, label in (("actions", "IF TRUE: "),):
                sub = node.get(key)
                if sub:
                    emit(sub, depth + 1, label)
            els = (node.get("else") or {}).get("actions")
            if els:
                emit(els, depth + 1, "IF FALSE: ")

    out.write("## The actions, in order\n\n")
    emit(defn["actions"], 0)

    out.write("""
## Test procedure — one synthetic submission

1. From the app (or the flow's Test pane) call the flow with a synthetic
   `submissionRequestId` (any fresh GUID-like string), a real pilot
   `installationId`/`reportingPeriod`/`requirementId` from your seeded
   data, and a small test file.
2. EXPECT: one new row in your Submission list with `Is_Current = Yes`,
   `Submission_Request_ID` equal to what you sent, and
   `SharePoint_Unique_ID` populated.
3. EXPECT: the file lands in the destination's matched month folder --
   or, if no month folder matches, at the configured ROOT with
   `Needs_Filing = Yes` and a `Filing_Note`. Either is correct behaviour;
   a file anywhere else is not.
4. Run the SAME call again, same `submissionRequestId`. EXPECT: no second
   row, no second file -- the response returns the first result
   (SUBMISSION_REPLAY). That is the idempotency guard working.
5. NOT TESTABLE LOCALLY, verified only here, in your tenant: connector
   auth, folder listings against the real site, and write permissions.
""")
    _writeif(os.path.join(KIT, "FLOW-BUILD", "EOM-02-manual.md"),
             out.getvalue())
    return counter[0]


