def build_sheets():
    lists = {l.name: l for l in S.LISTS}
    assert set(BUILD_ORDER) == set(lists), (
        "BUILD_ORDER drifted from the schema: "
        f"{set(BUILD_ORDER) ^ set(lists)}")
    totals = []
    for i, name in enumerate(BUILD_ORDER, 1):
        l = lists[name]
        unique = set(l.unique_key or ())
        cols = list(l.columns)
        n_idx = sum(1 for c in cols if c.indexed)
        totals.append((name, l.title, len(cols), n_idx))

        out = io.StringIO()
        out.write(f"# {i:02d} — create list `{l.title}`\n\n")
        out.write(INTERNAL_NAME_TRAP + "\n")
        out.write(f"**Site Contents → New → List → Blank list.** "
                  f"Name it exactly: `{l.title}`\n\n")
        if l.note:
            out.write(f"> {l.note.strip()}\n\n")
        out.write(f"Grain: {l.grain or 'see data model'} · expected volume "
                  f"~{l.volume_estimate:,} rows\n\n" if l.volume_estimate
                  else "\n")

        out.write("## Columns, in creation order\n\n")
        out.write("| # | Internal name (type EXACTLY) | Create as | "
                  "Settings | Required | Choices (verbatim) | Indexed | "
                  "Unique-key part |\n|---|---|---|---|---|---|---|---|\n")
        for n, c in enumerate(cols, 1):
            disp, settings = _type_settings(c)
            choices = "<br>".join(c.choices) if c.choices else ""
            out.write(f"| {n} | `{c.name}` | {disp} | {settings} | "
                      f"{'Yes' if c.required else 'No'} | {choices} | "
                      f"{'**Y**' if c.indexed else 'N'} | "
                      f"{'**Y**' if c.name in unique else 'N'} |\n")

        idx_cols = [c.name for c in cols if c.indexed]
        out.write(f"\n## Indexes — {n_idx} for this list\n\n")
        out.write("List settings → **Indexed columns** → Create a new "
                  "index, once per column below. Simple indexes only; no "
                  "compound indexes in this schema.\n\n")
        for cn in idx_cols:
            out.write(f"- [ ] `{cn}`\n")
        out.write("\n**Create every index NOW, while the list is empty.** "
                  "Past the 5,000-item List View Threshold, adding an index "
                  "to a large list is restricted and not to be counted on.\n")

        out.write(f"\n## VERIFY before moving on\n\n")
        out.write(f"- [ ] List settings shows **{len(cols)} columns you "
                  f"created** (SharePoint's own Title/ID/Modified rows are "
                  f"extra and do not count).\n")
        out.write(f"- [ ] Indexed columns shows **exactly {n_idx}**.\n")
        spot = next((c for c in cols if c.choices), None)
        if spot:
            out.write(f"- [ ] Spot check: `{spot.name}` offers exactly "
                      f"these choices, spelled exactly: "
                      f"{', '.join('`%s`' % v for v in spot.choices)}.\n")
        if unique:
            out.write(f"- [ ] Spot check: the unique-key column(s) "
                      f"{', '.join('`%s`' % u for u in sorted(unique))} "
                      f"exist with the exact internal names above. "
                      f"(Row uniqueness itself is enforced by the flows' "
                      f"idempotency logic, not by a SharePoint unique "
                      f"constraint — do NOT switch 'Enforce unique values' "
                      f"on unless the sheet's settings column says so.)\n")
        req = next((c for c in cols if c.required), None)
        if req:
            out.write(f"- [ ] Spot check: `{req.name}` is marked "
                      f"required.\n")
        _writeif(os.path.join(KIT, "LIST-BUILD-SHEETS",
                              f"{i:02d}-{name}.md"), out.getvalue())
    return totals


