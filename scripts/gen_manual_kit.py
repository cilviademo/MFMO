def _writeif(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def _type_settings(col):
    t = col.type
    if t == "Choice":
        return ("Choice", "Display choices in: Drop-Down Menu; "
                "Allow 'Fill-in' choices: No")
    if t == "Text":
        return ("Single line of text", "255 characters")
    if t == "Note":
        return ("Multiple lines of text", "Plain text")
    if t == "Number":
        return ("Number", "Decimal places: Automatic")
    if t == "Integer":
        return ("Number", "Decimal places: 0")
    if t == "Currency":
        return ("Currency", "")
    if t == "Boolean":
        return ("Yes/No", "Default: No")
    if t == "DateTime":
        return ("Date and Time", "Include Time: Yes")
    if t == "Date":
        return ("Date and Time", "Include Time: No")
    if t == "URL":
        return ("Hyperlink or Picture", "Format: Hyperlink")
    if t == "Person":
        return ("Person or Group", "Allow selection of: People Only")
    return (t, "")


