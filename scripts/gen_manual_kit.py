def main():
    if os.path.isdir(KIT):
        shutil.rmtree(KIT)

    totals = build_sheets()
    csv_path, fields, statuses = expected_items()
    n_actions = flow_manual()
    deferred_pages()

    n_lists = len(totals)
    n_cols = sum(t[2] for t in totals)
    n_idx = sum(t[3] for t in totals)
    assert (n_lists, n_cols, n_idx) == (17, 286, 90), (n_lists, n_cols, n_idx)

    # ---- CSV-IMPORT ----
    seeds = [f for f in sorted(os.listdir(os.path.join(ROOT, "configuration")))
             if f.endswith(".csv") and ".sample." not in f]
    os.makedirs(os.path.join(KIT, "CSV-IMPORT"), exist_ok=True)
    counts = {}
    for f in seeds:
        src = os.path.join(ROOT, "configuration", f)
        shutil.copy(src, os.path.join(KIT, "CSV-IMPORT", f))
        with open(src, encoding="utf-8-sig") as fh:
            counts[f] = sum(1 for _ in fh) - 1

    status_lines = "\n".join(f"  {k}: {v} rows"
                             for k, v in sorted(statuses.items()))
    imp = io.StringIO()
    imp.write("# CSV import — grid-view paste, list by list\n\n")
    imp.write("**Never use \"New list → From Excel\"** — it creates its own "
              "columns with its own internal names and silently orphans "
              "every formula in this kit. The lists already exist (the "
              "build sheets made them); these CSVs fill them.\n\n"
              "Per CSV: open the target list → **Edit in grid view** → in "
              "a spreadsheet, arrange the CSV's columns into the SAME "
              "order as the grid → copy the data rows → click the first "
              "empty cell → paste → wait for every cell to commit → "
              "count.\n\n")
    imp.write("| CSV | Target list | Rows to paste | After paste, list "
              "shows |\n|---|---|---:|---|\n")
    title_by_csvish = {
        "app-config.csv": "MF App Config",
        "feature-flags.csv": "MF Feature Flags",
        "installations.csv": "MF Installation",
        "facilities.csv": "MF Facility",
        "requirements.csv": "MF EOM Requirement",
        "document-destinations.csv": "MF Document Destination",
        "notification-rules.csv": "MF Notification Rule",
        "pilot-onboarding.csv": "(worksheet — read, do not paste)",
        "qrg-data-quality.csv": "(worksheet — read, do not paste)",
        "expected-items-2026-08-09.csv": "MF EOM Item",
    }
    for f in seeds:
        tgt = title_by_csvish.get(f, "(see guide)")
        imp.write(f"| `{f}` | {tgt} | {counts[f]} | "
                  f"{counts[f]} items |\n")
    imp.write(f"""
## expected-items-2026-08-09.csv — read this before pasting

Generated OFFLINE by the same EOM-01 engine the test suite runs: full R1
scope (43 installations, 67 Legacy facilities), periods 2026-08 and
2026-09, **exactly 737 rows**. Statuses are computed by the status engine
**as of {AS_OF.isoformat()}** and come out:

{status_lines}

They will NOT refresh on their own during the manual pilot (EOM-03 is
deferred); EOM-02 updates a row when a submission lands, and the rest
stay as seeded until reconciliation exists. That is expected, not a
defect. Blank cells in the CSV are deliberate nulls — paste them as
empty, never as the text "null".
""")
    _writeif(os.path.join(KIT, "CSV-IMPORT", "IMPORT-ORDER.md"),
             imp.getvalue())

    # ---- CANVAS-MANUAL ----
    shutil.copytree(os.path.join(ROOT, "canvas-app", "src"),
                    os.path.join(KIT, "CANVAS-MANUAL", "src"))
    shutil.copytree(os.path.join(ROOT, "canvas-app", "formulas"),
                    os.path.join(KIT, "CANVAS-MANUAL", "formulas"))

    # ---- VERIFICATION ----
    ver = io.StringIO()
    ver.write("# VERIFICATION — sign this before any CSV touches any "
              "list\n\n**Loading configuration before this gate is signed "
              "is forbidden.** An index missed here is found now, while "
              "every list is empty and every index is still cheap to "
              "create.\n\n")
    ver.write("| # | List | Columns expected | Columns found | Indexes "
              "expected | Indexes found | PASS |\n"
              "|---|---|---:|---|---:|---|---|\n")
    for i, (name, title, nc, ni) in enumerate(totals, 1):
        ver.write(f"| {i:02d} | `{title}` | {nc} |    | {ni} |    |    |\n")
    ver.write(f"| | **TOTAL** | **{n_cols}** | | **{n_idx}** | | |\n\n")
    ver.write("The six lists that will grow past 5,000 rows, where a "
              "missing index hurts most:\n\n")
    for nm, exp in (("MF_EOM_Item", 13), ("MF_EOM_Submission", 13),
                    ("MF_EOM_Status", 8), ("MF_Security_Mapping", 8),
                    ("MF_App_Event_Log", 6), ("MF_EOM_Audit", 4)):
        actual = dict((t[0], t[3]) for t in totals)[nm]
        assert actual == exp, (nm, actual, exp)
        ver.write(f"- [ ] `{nm}`: **{exp}** indexes\n")
    ver.write("\n```\nSAFE TO LOAD CONFIGURATION:  YES / NO\n"
              "Signed:                      ____________  Date: ______\n"
              "```\n\nYES only when every row above reads PASS. "
              "Row-level behaviour in the tenant (throttling, threshold "
              "behaviour at 5,000+) is NOT TESTABLE LOCALLY and is not "
              "claimed here.\n")
    _writeif(os.path.join(KIT, "VERIFICATION.md"), ver.getvalue())

    canvas_runbook()
    build_guide(totals, statuses)

    with open(os.path.join(KIT, "kit-facts.json"), "w",
              encoding="utf-8") as fh:
        json.dump({"lists": n_lists, "columns": n_cols, "indexes": n_idx,
                   "expected_rows": 737, "as_of": AS_OF.isoformat(),
                   "statuses": statuses, "flow_actions": n_actions,
                   "per_list": [[t[0], t[2], t[3]] for t in totals]},
                  fh, indent=1)
    print(f"kit: {KIT}")
    print(f"  {n_lists} lists / {n_cols} columns / {n_idx} indexes; "
          f"expected-items rows: 737; statuses: {statuses}; "
          f"flow actions documented: {n_actions}")
    return 0


