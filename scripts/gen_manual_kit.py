def load_cfg(name):
    with open(os.path.join(ROOT, "configuration", name),
              encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def expected_items():
    facs = load_cfg("facilities.csv")
    insts = load_cfg("installations.csv")
    r1 = {f["Installation_ID"] for f in facs if f["In_R1_Scope"] == "TRUE"}
    full = [dict(i,
                 Generation_Enabled=("TRUE" if i["Installation_ID"] in r1
                                     else "FALSE"),
                 Registry_Validated_By="manual-kit",
                 Registry_Validated_Date="2026-08-31") for i in insts]
    rows = {}
    for p in periods_in_window("2026-08", "2026-09"):
        r, _ = generate(load_cfg("requirements.csv"), full, facs, p,
                        existing=dict(rows), today=AS_OF,
                        non_duty_days=load_cfg("non-duty-days.sample.csv"))
        rows.update(r)
    if len(rows) != 737:
        raise SystemExit(
            f"STOP: the engine generated {len(rows)} rows, not 737. "
            f"The pilot was resized or a seed drifted -- report the delta, "
            f"do not ship this CSV.")
    ordered = sorted(rows.values(), key=lambda r: r["EOM_Item_ID"])
    fields = list(ordered[0].keys())
    out = os.path.join(ROOT, "configuration", "expected-items-2026-08-09.csv")
    with open(out, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        for r in ordered:
            w.writerow({k: ("" if v is None else v) for k, v in r.items()})
    statuses = {}
    for r in ordered:
        statuses[r["Final_Status"]] = statuses.get(r["Final_Status"], 0) + 1
    return out, fields, statuses


