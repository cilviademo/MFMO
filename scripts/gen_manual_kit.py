def _sub_params(text):
    """@parameters('MF_X (mfops_MF_X)') -> @variables('varMF_X')."""
    import re
    return re.sub(r"(@?)parameters\('(MF_[A-Za-z0-9_]+) \(mfops_[A-Za-z0-9_]+\)'\)",
                  lambda m: f"{m.group(1)}variables('var{m.group(2)}')", text)


